/**
 * Traduz textos dinâmicos de toasts ou notificações para o inglês
 */
export function translateToastToEnglish(text: string): string {
  const trimmed = text.trim();
  if (toastTranslationMap[trimmed]) {
    return toastTranslationMap[trimmed];
  }

  // Padrões dinâmicos com Regex
  let match = trimmed.match(/^Seu nome foi alterado .*? para "(.*?)"\.$/);
  if (match) return `Your name was updated to "${match[1]}".`;

  match = trimmed.match(/^Seu novo identificador @(.*?) foi salvo/);
  if (match) return `Your new handle @${match[1]} was saved.`;

  match = trimmed.match(/^O @(.*?) já está em uso por outra conta\./);
  if (match) return `The @${match[1]} handle is already in use by another account.`;

  match = trimmed.match(/^O identificador @(.*?) já está em uso/);
  if (match) return `The handle @${match[1]} is already in use by another user.`;

  match = trimmed.match(/^Removido de (.*)/);
  if (match) return `Removed from ${match[1]}`;

  match = trimmed.match(/^Adicionado a (.*)/);
  if (match) return `Added to ${match[1]}`;

  match = trimmed.match(/^Você saiu do modo (.*?)\. Nova conversa iniciada\.$/);
  if (match) return `You exited ${match[1]} mode. New conversation started.`;

  match = trimmed.match(/^Você ainda pode traduzir mais (\d+) capítulos hoje\.$/);
  if (match) return `You can still translate ${match[1]} more chapters today.`;

  match = trimmed.match(/^Dia (\d+) Concluído e Salvo!$/);
  if (match) return `Day ${match[1]} Completed and Saved!`;

  match = trimmed.match(/^Dia (\d+) Concluído$/);
  if (match) return `Day ${match[1]} Completed`;

  return text;
}
